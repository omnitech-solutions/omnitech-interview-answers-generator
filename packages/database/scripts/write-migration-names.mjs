// Regenerates src/migration-names.ts: the migration folders of the Drizzle
// stream, in order. The bundled apps (agent-worker, terminal-gateway) cannot
// read `drizzle/` at runtime, so the boot-time check embeds the names.
//
//   pnpm --filter @omnitech/database run db:names
//
// Run from packages/database; `db:generate` runs it after drizzle-kit.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The migration folder names, in timestamp order. */
export function migrationFolderNames(folder = join(root, "drizzle")) {
  return readdirSync(folder, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && /^\d+_/.test(entry.name))
    .map((entry) => entry.name)
    .sort();
}

export function renderMigrationNames(names = migrationFolderNames()) {
  return `// Generated by scripts/write-migration-names.mjs: do not edit by hand.
// Regenerate with \`pnpm --filter @omnitech/database run db:names\`.
export const expectedMigrations: readonly string[] = [
${names.map((name) => `  "${name}",`).join("\n")}
];
`;
}

if (import.meta.url === `file://${process.argv[1]}`)
  writeFileSync(join(root, "src", "migration-names.ts"), renderMigrationNames());
