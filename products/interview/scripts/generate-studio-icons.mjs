// Writes the Material Symbols Rounded paths the studio uses into
// src/frontend/studio/icons.generated.ts. Run after changing the list:
//   pnpm --filter @omnitech/product-interview icons
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const icons = [
  "add", "arrow_upward", "cancel", "check", "check_circle",
  "chevron_left", "chevron_right", "close", "cloud_done", "code",
  "content_copy", "contrast", "dark_mode", "error", "event", "expand_less",
  "expand_more", "forum", "home", "light_mode", "lightbulb", "lock",
  "looks_3", "looks_4", "looks_5", "looks_one", "looks_two", "menu_book",
  "mic", "pause", "pause_circle", "pending", "play_arrow", "play_circle",
  "priority_high", "record_voice_over", "refresh", "science", "search",
  "search_off", "terminal", "timer", "verified",
  "visibility", "visibility_off", "warning",
];
// Studio names whose source file was renamed upstream. The assistant sparkle
// (auto_awesome) is not here: icon.tsx renders the assistant package's own.
const sources = {
  expand_less: "keyboard_arrow_up",
  expand_more: "keyboard_arrow_down",
};
const require = createRequire(import.meta.url);
const root = join(
  dirname(require.resolve("@material-symbols/svg-400/package.json")),
  "rounded",
);
const path = (file) =>
  /<path d="([^"]+)"/.exec(readFileSync(join(root, file), "utf8"))[1];
const entries = [...new Set([...icons, ...Object.keys(sources)])].sort().flatMap((name) => {
  const file = sources[name] ?? name;
  return [
    `  ${name}: ${JSON.stringify(path(`${file}.svg`))},`,
    `  "${name}-fill": ${JSON.stringify(path(`${file}-fill.svg`))},`,
  ];
});
writeFileSync(
  new URL("../src/frontend/studio/icons.generated.ts", import.meta.url),
  `// GENERATED by scripts/generate-studio-icons.mjs from @material-symbols/svg-400
// (rounded, weight 400, Apache-2.0). viewBox "0 -960 960 960". Do not edit.
export const ICON_PATHS = {
${entries.join("\n")}
} as const;
`,
);
console.log(`Wrote ${entries.length / 2} icons.`);
