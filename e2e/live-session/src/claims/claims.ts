// The claims inventory: every interactive control of the live session, on the
// web page and in the native panel, with WHAT ITS LABEL OR TOOLTIP SAYS IT DOES
// and what REAL effect proves that. The rule of this suite: a control is covered
// only by a spec that observes the effect named here (a server row, an HTTP
// result, a recorded native bridge call, clipboard contents, a DOM change only
// the real behaviour can produce), never by the control merely being present.
//
// `claims-coverage.spec.ts` scans the rendered pages and FAILS on a control that
// is not matched below, and on a `covered` entry whose spec title does not exist.
// `pending` entries are the worklist: they fail the run only with E2E_STRICT=1.
// To cover one: write the spec, set `status: "covered"` and `spec` to a
// substring of its title.
export type Surface = "web" | "native";

export type EffectKind =
  | "server" // a row or HTTP result the server holds
  | "bridge" // a recorded native host call (window.studioHost)
  | "clipboard" // navigator.clipboard contents
  | "dom" // a state change only the real behaviour can produce
  | "navigation"; // the URL or window the control leads to

export type Claim = {
  id: string;
  surface: Surface;
  // The part of the page that owns the control.
  where: string;
  role: string;
  // Matched against the accessible name: exact string, or a pattern for names
  // that carry times, ordinals or state.
  name: string | RegExp;
  // What the label, tooltip or surrounding copy says the control does.
  claim: string;
  effect: { kind: EffectKind; detail: string };
  status: "covered" | "pending";
  // A substring of the title of the spec that asserts the effect.
  spec?: string;
};

type Row = [
  id: string,
  where: string,
  role: string,
  name: string | RegExp,
  claim: string,
  kind: EffectKind,
  detail: string,
  spec?: string,
];

const make = (surface: Surface, rows: Row[]): Claim[] =>
  rows.map(([id, where, role, name, claim, kind, detail, spec]) => ({
    id,
    surface,
    where,
    role,
    name,
    claim,
    effect: { kind, detail },
    status: spec ? "covered" : "pending",
    ...(spec ? { spec } : {}),
  }));

