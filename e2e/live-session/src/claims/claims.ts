// A claim names its spec in ONE place: a row's own `spec` or COVERED_BY. When
// both name a spec and they differ, the claims-coverage spec fails on it.
export const SPEC_DISAGREEMENTS: string[] = [];
for (const claim of [...WEB_CLAIMS, ...NATIVE_CLAIMS]) {
  const spec = COVERED_BY[claim.id];
  if (!spec) continue;
  if (claim.spec && claim.spec !== spec)
    SPEC_DISAGREEMENTS.push(
      `${claim.id}: row says "${claim.spec}", COVERED_BY says "${spec}"`,
    );
  else if (!claim.spec) {
    claim.status = "covered";
    claim.spec = spec;
  }
}

export const CLAIMS: Claim[] = [...WEB_CLAIMS, ...NATIVE_CLAIMS];

export function matches(claim: Claim, role: string, name: string): boolean {
  if (claim.role !== role) return false;
  return typeof claim.name === "string"
    ? claim.name === name
    : claim.name.test(name);
}

export const findClaim = (
  surface: Surface,
  role: string,
  name: string,
): Claim | undefined =>
  CLAIMS.find(
    (claim) => claim.surface === surface && matches(claim, role, name),
  );
